
import sqlite3
import requests
import sqlglot
import time

from sqlglot import exp
from sqlglot.optimizer.scope import traverse_scope

DB_PATH = "sales.db"
MODEL = "qwen2.5-coder:3b"
OLLAMA_URL = "http://localhost:11434/api/generate"

ALLOWED_TABLES = {
    "orders",
    "customers",
    "products",
    "payments"
}

session = requests.Session()


# --------------------------------------------------
# OLLAMA REQUEST
# --------------------------------------------------

def ask_ollama(prompt, max_tokens=200):
    """Send a prompt to the local Ollama model."""

    response = session.post(
        OLLAMA_URL,
        json={
            "model": MODEL,
            "prompt": prompt,
            "stream": False,
            "keep_alive": "10m",
            "options": {
                "temperature": 0,
                "num_predict": max_tokens,
                "num_ctx": 2048
            }
        },
        timeout=120
    )

    response.raise_for_status()

    return response.json()["response"].strip()


# --------------------------------------------------
# DATABASE SCHEMA
# --------------------------------------------------

def get_schema():
    """Retrieve table and column information only."""

    schema_parts = []

    with sqlite3.connect(DB_PATH) as conn:

        for table in sorted(ALLOWED_TABLES):

            rows = conn.execute(
                f"PRAGMA table_info({table})"
            ).fetchall()

            if not rows:
                raise ValueError(
                    f"The {table} table was not found."
                )

            columns = ", ".join(
                f"{row[1]} ({row[2]})"
                for row in rows
            )

            schema_parts.append(
                f"Table {table}: {columns}"
            )

    relationships = """
DATABASE RELATIONSHIPS:
- orders.customer_id = customers.customer_id
- payments.order_id = orders.order_id
- orders.product_name = products.product_name

COLUMN MEANINGS:
- customers.region: Customer's region.
- customers.state: Customer's state.
- orders.region: Region recorded for an order.
- orders.profit: Profit generated by an order.
- orders.sales: Revenue generated by an order.
- products.unit_price: Product unit price.
"""

    return "\n".join(schema_parts) + relationships


# --------------------------------------------------
# GENERATE SQL USING OLLAMA
# --------------------------------------------------

def generate_sql(question):
    """
    Ollama receives only:
    1. User question
    2. Database schema

    No actual database records or query results
    are sent to Ollama.
    """

    schema = get_schema()

    prompt = f"""
You are an expert SQLite SQL assistant.

Generate exactly one valid SQLite SELECT query
to answer the user's question.

RULES:
1. Use only the provided tables and columns.
2. Use correct JOIN relationships.
3. Never invent table or column names.
4. Generate only SELECT statements.
5. Never generate INSERT, UPDATE, DELETE,
   DROP, ALTER, CREATE or other modifications.
6. Use AND when all conditions must be true.
7. Use OR when either condition can be true.
8. Preserve the logical operator in the question.
9. "Both" means AND.
10. "Either" means OR.
11. Use SUM() for total sales and total profit.
12. Use COUNT() to count records.
13. Use GROUP BY for grouped results.
14. Use ORDER BY and LIMIT for top or bottom results.
15. Return only SQL without Markdown or explanations.

DATABASE SCHEMA:
{schema}

USER QUESTION:
{question}

Generate the SQLite query:
"""

    start = time.perf_counter()

    sql = ask_ollama(prompt, max_tokens=250)

    print(
        f"SQL generation time: "
        f"{time.perf_counter() - start:.2f} seconds"
    )

    # Remove Markdown code fences if present
    sql = sql.replace("```sql", "").replace("```", "").strip()

    return sql


# --------------------------------------------------
# VALIDATE AND EXECUTE SQL
# --------------------------------------------------

def execute_sql(sql):
    """
    Validate and execute read-only SQL queries.

    Supports SELECT, UNION, INTERSECT, EXCEPT
    and SELECT-based CTE queries.

    Only authorized physical database tables
    are allowed.
    """

    # 1. Parse SQL using SQLGlot
    statements = sqlglot.parse(sql, read="sqlite")

    # 2. Allow exactly one SQL statement
    if len(statements) != 1 or statements[0] is None:
        raise ValueError(
            "Only one SQL statement is allowed."
        )

    tree = statements[0]

    # 3. Allow only SELECT-based query types
    allowed_query_types = (
        exp.Select,
        exp.Union,
        exp.Intersect,
        exp.Except
    )

    if not isinstance(tree, allowed_query_types):
        raise ValueError(
            "Only SELECT queries are allowed."
        )

    # 4. Identify physical tables using SQLGlot scopes.
    # CTE references are represented as Scope objects,
    # while actual database tables are represented as Table objects.

    tables = set()

    for scope in traverse_scope(tree):

        for source in scope.sources.values():

            if isinstance(source, exp.Table):
                tables.add(source.name.lower())

    # 5. Require at least one physical database table
    if not tables:
        raise ValueError(
            "Query must reference an authorized table."
        )

    # 6. Reject unauthorized physical tables
    if not tables.issubset(ALLOWED_TABLES):
        raise ValueError(
            "Query references an unauthorized table."
        )

    # 7. Execute using SQLite read-only mode
    start = time.perf_counter()

    with sqlite3.connect(DB_PATH) as conn:

        conn.execute("PRAGMA query_only = ON")

        cursor = conn.execute(sql)

        # Check whether query returns columns
        if cursor.description is None:
            raise ValueError(
                "Query did not return tabular results."
            )

        # Get column names
        columns = [
            item[0] for item in cursor.description
        ]

        # Fetch maximum 100 rows
        rows = cursor.fetchmany(100)

    print(
        f"SQL execution time: "
        f"{time.perf_counter() - start:.2f} seconds"
    )

    return columns, rows


# --------------------------------------------------
# MAIN PROGRAM - TESTING
# --------------------------------------------------

if __name__ == "__main__":

    question = "What is the total profit?"

    try:

        total_start = time.perf_counter()

        # Step 1: Generate SQL using Ollama
        sql = generate_sql(question)

        print("\nGenerated SQL:\n")
        print(sql)

        # Step 2: Validate and execute SQL
        columns, rows = execute_sql(sql)

        # Step 3: Display actual database results
        print("\nQuery Results:\n")
        print(columns)

        for row in rows:
            print(row)

        print(
            f"\nTotal time: "
            f"{time.perf_counter() - total_start:.2f} seconds"
        )

    except Exception as error:
        print("\nError:", error)
