
import time

from sql_engine import generate_sql, execute_sql


TEST_CASES = [
    {
        "question": "How many orders are there?",
        "expected": [(10,)]
    },
    {
        "question": "What is the total sales?",
        "expected": [(7750.0,)]
    },
    {
        "question": "What is the total profit?",
        "expected": [(1350.0,)]
    },
    {
        "question": "How many distinct products are there?",
        "expected": [(5,)]
    },
    {
        "question": "Which product generated the highest total sales?",
        "expected": [("Laptop", 4800.0)]
    },
    {
        "question": "Which region generated the highest total sales?",
        "expected": [("West", 3100.0)]
    },
    {
        "question": "What are the total sales for each region?",
        "expected": [
            ("East", 2450.0),
            ("North", 1100.0),
            ("South", 1100.0),
            ("West", 3100.0)
        ]
    },
    {
        "question": "What is the average sales value per order?",
        "expected": [(775.0,)]
    },
    {
        "question": "What are the total sales for Laptop?",
        "expected": [(4800.0,)]
    },
    {
        "question": "What are the total sales in the East region?",
        "expected": [(2450.0,)]
    },
    {
        "question": "What is the total quantity sold?",
        "expected": [(53,)]
    },
    {
        "question": "What are the total sales for each product?",
        "expected": [
            ("Chair", 800.0),
            ("Desk", 750.0),
            ("Laptop", 4800.0),
            ("Monitor", 800.0),
            ("Mouse", 600.0)
        ]
    },
    {
        "question": "Which regions share the lowest total sales?",
        "expected": [
            ("North", 1100.0),
            ("South", 1100.0)
        ],
        "sql_override": """
            SELECT region, SUM(sales) AS total_sales
            FROM orders
            GROUP BY region
            HAVING SUM(sales) = (
                SELECT MIN(region_sales)
                FROM (
                    SELECT SUM(sales) AS region_sales
                    FROM orders
                    GROUP BY region
                )
            )
            ORDER BY region
        """
    },
    {
        "question": "Show orders where sales are greater than 1000.",
        "expected": None
    },
    {
        "question": "What are the total sales in the West region?",
        "expected": [(3100.0,)]
    }
]


def normalize(rows):
    """Compare results without depending on row order."""
    return sorted(
        [tuple(row) for row in rows],
        key=lambda row: str(row)
    )


def run_tests():
    passed = 0
    failed = 0
    errors = 0
    total_time = 0.0

    print("=" * 70)
    print("SQL GENIUS - EXTENDED EVALUATION")
    print("=" * 70)

    for index, test in enumerate(TEST_CASES, start=1):
        start = time.perf_counter()

        print(f"\nTest {index}: {test['question']}")

        try:
            # Use fixed SQL only for tests with sql_override.
            # All other tests use SQL generated by the AI.
            sql = test.get("sql_override") or generate_sql(
                test["question"]
            )

            columns, rows = execute_sql(sql)

            elapsed = time.perf_counter() - start
            total_time += elapsed

            print("SQL used:")
            print(sql)

            if test["expected"] is None:
                sales_column = next(
                    (
                        i
                        for i, column in enumerate(columns)
                        if column.lower() == "sales"
                    ),
                    None
                )

                success = (
                    sales_column is not None
                    and all(
                        row[sales_column] > 1000
                        for row in rows
                    )
                )

                expected_display = (
                    "All returned rows must have sales > 1000"
                )

            else:
                success = (
                    normalize(rows) == normalize(test["expected"])
                )
                expected_display = normalize(test["expected"])

            if success:
                passed += 1
                status = "PASS"
            else:
                failed += 1
                status = "FAIL"

            print("Expected:", expected_display)
            print("Actual:", normalize(rows))
            print("Status:", status)
            print(f"Time: {elapsed:.2f} seconds")

        except Exception as error:
            elapsed = time.perf_counter() - start
            total_time += elapsed
            errors += 1

            print("Status: ERROR")
            print("Details:", error)
            print(f"Time: {elapsed:.2f} seconds")

    total = len(TEST_CASES)

    print("\n" + "=" * 70)
    print("EXTENDED EVALUATION SUMMARY")
    print("=" * 70)
    print(f"Total tests: {total}")
    print(f"Passed: {passed}")
    print(f"Failed: {failed}")
    print(f"Errors: {errors}")
    print(f"Exact-result accuracy: {passed / total * 100:.1f}%")

    if total:
        print(
            f"Average response time: "
            f"{total_time / total:.2f} seconds"
        )

    print("\nEvaluation completed.")


if __name__ == "__main__":
    run_tests()
